const p = (text: string): Block => ({ type: "p", text });
const h2 = (id: string, text: string): Block => ({ type: "h2", id, text });
const h3 = (id: string, text: string): Block => ({ type: "h3", id, text });
const ul = (...items: string[]): Block => ({ type: "list", items });
const ol = (...items: string[]): Block => ({ type: "list", ordered: true, items });
const warn = (text: string): Block => ({ type: "callout", tone: "warning", text });
const info = (text: string): Block => ({ type: "callout", tone: "info", text });
const table = (head: string[], ...rows: string[][]): Block => ({ type: "table", head, rows });

type Def = {
  slug: string;
  title: string;
  description: string;
  seoTitle?: string;
  cats: CategoryId[];
  subs?: SubcategoryId[];
  tags?: TagId[];
  image?: ImageKey;
  related?: ContentId[];
  updatedAt?: string;
  content: Block[];
};

const make = (d: Def): Article => ({
  id: `article:${d.slug}` as ArticleId,
  kind: "article",
  slug: d.slug,
  title: d.title,
  description: d.description,
  status: "published",
  seo: { title: d.seoTitle ?? d.title, description: d.description },
  primaryCategory: d.cats[0]!,
  categories: d.cats,
  ...(d.subs ? { subcategories: d.subs } : {}),
  ...(d.tags ? { tags: d.tags } : {}),
  ...(d.image ? { image: IMAGES[d.image] } : {}),
  ...(d.related ? { related: d.related } : {}),
  ...(d.updatedAt ? { updatedAt: d.updatedAt } : {}),
  content: d.content,
});

